import { readdir, readFile } from "node:fs/promises";
import { format, resolveConfig } from "prettier";
import { expect, it } from "vitest";
import { z } from "zod";

import { openapi } from "./openapi.js";
import { createSchema, listQuerySchema } from "./validation/products.js";

interface Schema {
  additionalProperties?: Schema;
  anyOf?: Schema[];
  default?: unknown;
  description?: string;
  enum?: string[];
  maximum?: number;
  maxLength?: number;
  maxProperties?: number;
  minimum?: number;
  minLength?: number;
  pattern?: string;
  properties?: Record<string, Schema>;
  propertyNames?: Schema;
  required?: string[];
  type?: string;
}

const jsonSchema = (schema: z.ZodType) =>
  z.toJSONSchema(schema, { io: "input" }) as Schema;
const code = (value: unknown) => `\`${String(value)}\``;
const count = (value: number) => value.toLocaleString("en-US");
const either = (items: string[]) =>
  new Intl.ListFormat("en-GB", { type: "disjunction" }).format(items);

function fill(readme: string, block: string, content: string) {
  const pattern = new RegExp(
    `(<!-- ${block}: generated by src/docs.test.ts -->\\n)[\\s\\S]*?(<!-- end -->)`,
  );
  expect(readme, `README.md has no ${block} block`).toMatch(pattern);
  return readme.replace(
    pattern,
    (_match, start: string, end: string) => `${start}${content}\n${end}`,
  );
}

function length({ maxLength, minLength }: Schema) {
  if (maxLength === undefined) return [];
  return minLength
    ? [`${count(minLength)} to ${count(maxLength)} characters`]
    : [`up to ${count(maxLength)} characters`];
}

function limits(schema: Schema): string[] {
  const values = schema.anyOf?.filter((branch) => branch.type !== "null");
  if (values?.length === 1 && values[0])
    return [...limits(values[0]), "or null"];
  switch (schema.type) {
    case "integer":
      return [
        `integer from ${count(schema.minimum ?? 0)} to ${count(schema.maximum ?? 0)}`,
      ];
    case "object":
      return [
        `up to ${String(schema.maxProperties)} keys of ${length(schema.propertyNames ?? {}).join("")}. Values are ${either(
          (schema.additionalProperties?.anyOf ?? []).map((value) =>
            value.type === "string"
              ? `strings of ${length(value).join("")}`
              : `${String(value.type)}s`,
          ),
        )}`,
      ];
    case "string":
      return [
        ...(schema.enum ? [`one of ${schema.enum.map(code).join(", ")}`] : []),
        ...length(schema),
        ...(schema.pattern ? [`matching ${code(schema.pattern)}`] : []),
      ];
    default:
      return [];
  }
}

function rules(schema: Schema) {
  const defaults =
    schema.default === undefined ||
    schema.default === null ||
    typeof schema.default === "object"
      ? []
      : [`default ${code(schema.default)}`];
  const text = [...limits(schema), ...defaults].join(", ");
  return [text.charAt(0).toUpperCase() + text.slice(1), schema.description]
    .filter(Boolean)
    .map((sentence) => `${String(sentence)}.`.replace(/\.\.$/, "."))
    .join(" ");
}

function table(schema: z.ZodType, first: string) {
  const { properties = {}, required = [] } = jsonSchema(schema);
  const rows = Object.entries(properties).map(([name, property]) => [
    code(name),
    required.includes(name) ? "Yes" : "No",
    rules(property),
  ]);
  return [[first, "Required", "Rules"], ["---", "---", "---"], ...rows]
    .map((row) => `| ${row.join(" | ")} |`)
    .join("\n");
}

it("README.md tables match the zod schemas (npx vitest -u src/docs.test.ts rewrites them)", async () => {
  let readme = await readFile("README.md", "utf8");
  readme = fill(readme, "fields", table(createSchema, "Field"));
  readme = fill(readme, "list query", table(listQuerySchema, "Parameter"));
  const options = await resolveConfig("README.md");
  await expect(
    await format(readme, { ...options, parser: "markdown" }),
  ).toMatchFileSnapshot("../README.md");
});

it("the docs name only routes that exist", async () => {
  const records = await readdir("docs/adr");
  for (const file of [
    "README.md",
    ...records.map((record) => `docs/adr/${record}`),
  ]) {
    const text = await readFile(file, "utf8");
    for (const [, method = "", path = ""] of text.matchAll(
      /\b(DELETE|GET|PATCH|POST|PUT) (\/[\w/:{}-]*)/g,
    )) {
      const operation =
        openapi.paths[path.replace(/:(\w+)/g, "{$1}")]?.[method.toLowerCase()];
      expect(
        operation,
        `${file} names ${method} ${path}, which src/openapi.ts does not document`,
      ).toBeDefined();
    }
  }
});

it("the README layout lists every directory in src", async () => {
  const readme = await readFile("README.md", "utf8");
  for (const entry of await readdir("src", { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    expect(
      readme,
      `the src/ layout in README.md does not list ${entry.name}/`,
    ).toMatch(new RegExp(`^  ${entry.name}/`, "m"));
  }
});
